// Writes Sources/ZBC/CommandsGen.swift from ../spec/transactions/*.json so the package carries its
// own command table. Run from swift/: swift run gen   (CI checks the result is current).
import Foundation

let fm = FileManager.default
let specDir = URL(fileURLWithPath: "../spec/transactions")
let names = try fm.contentsOfDirectory(atPath: specDir.path).filter { $0.hasSuffix(".json") && $0 != "index.json" }.sorted()
var defs: [[String: Any]] = []
for n in names {
    let data = try Data(contentsOf: specDir.appendingPathComponent(n))
    var obj = try JSONSerialization.jsonObject(with: data) as! [String: Any]
    obj.removeValue(forKey: "license")
    defs.append(obj)
}
let json = String(decoding: try JSONSerialization.data(withJSONObject: defs, options: [.prettyPrinted, .sortedKeys]), as: UTF8.self)
let hashes = String(repeating: "#", count: 4)
var out = "// SPDX-License-Identifier: MIT\n// Copyright (c) 2024-2026 ZooBC Foundation and Roberto Capodieci\n\n"
out += "// GENERATED by `swift run gen` from spec/transactions/*.json. Do not edit.\n\n"
out += "let commandsJSON = \(hashes)\"\"\"\n\(json)\n\"\"\"\(hashes)\n"
try out.write(toFile: "Sources/ZBC/CommandsGen.swift", atomically: true, encoding: .utf8)
print("generated Sources/ZBC/CommandsGen.swift (\(defs.count) commands)")
