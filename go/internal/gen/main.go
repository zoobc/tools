// Command gen writes zbc/commands_gen.go from ../spec/transactions/*.json and one main package per
// tool binary under cmd/. Run from go/: go run ./internal/gen   (CI checks the result is current).
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "// SPDX-License-Identifier: MIT\n// Copyright (c) 2024-2026 ZooBC Foundation and Roberto Capodieci\n"

func main() {
	specDir := filepath.Join("..", "spec", "transactions")
	entries, err := os.ReadDir(specDir)
	check(err)
	var defs []map[string]any
	var names []string
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".json") || e.Name() == "index.json" {
			continue
		}
		names = append(names, e.Name())
	}
	sort.Strings(names)
	for _, n := range names {
		raw, err := os.ReadFile(filepath.Join(specDir, n))
		check(err)
		var d map[string]any
		check(json.Unmarshal(raw, &d))
		delete(d, "license")
		defs = append(defs, d)
	}
	text, err := json.MarshalIndent(defs, "", " ")
	check(err)
	var sb strings.Builder
	sb.WriteString(header)
	sb.WriteString("\n// GENERATED by internal/gen from spec/transactions/*.json. Do not edit.\n\npackage zbc\n\nconst commandsJSON = `")
	sb.WriteString(strings.ReplaceAll(string(text), "`", "` + \"`\" + `"))
	sb.WriteString("`\n")
	check(os.WriteFile(filepath.Join("zbc", "commands_gen.go"), []byte(sb.String()), 0o644))

	// One program per tool binary, as the C++ tools have.
	count := 0
	for _, d := range defs {
		bin, _ := d["binary"].(string)
		if bin == "" {
			continue
		}
		dir := filepath.Join("cmd", bin)
		check(os.MkdirAll(dir, 0o755))
		src := fmt.Sprintf("%s\n// GENERATED by internal/gen: the %s command as its own program.\n\npackage main\n\nimport (\n\t\"os\"\n\n\t\"github.com/zoobc/tools/go/cli\"\n)\n\nfunc main() { os.Exit(cli.RunTool(%q, os.Args[1:], os.Stdin, os.Stdout, os.Stderr)) }\n",
			header, d["command"], d["command"])
		check(os.WriteFile(filepath.Join(dir, "main.go"), []byte(src), 0o644))
		count++
	}
	fmt.Printf("generated zbc/commands_gen.go (%d commands) and %d cmd/ programs\n", len(defs), count)
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
