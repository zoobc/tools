// Embed spec/transactions/*.json into src/generated/commands.ts so the package carries its own
// command table. Run from ts/: node scripts/gen-commands.mjs   (CI checks the result is current)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specDir = join(here, "..", "..", "spec", "transactions");
const defs = readdirSync(specDir).filter((f) => f.endsWith(".json") && f !== "index.json").sort()
  .map((f) => JSON.parse(readFileSync(join(specDir, f), "utf8")));
for (const d of defs) delete d.license;
const out = `// SPDX-License-Identifier: MIT
// Copyright (c) 2024-2026 ZooBC Foundation and Roberto Capodieci
// GENERATED by scripts/gen-commands.mjs from spec/transactions/*.json. Do not edit.
import type { TxDef } from "../spec.js";

export const COMMANDS: readonly TxDef[] = ${JSON.stringify(defs, null, 1)};

export const COMMAND_BY_NAME: ReadonlyMap<string, TxDef> = new Map(COMMANDS.map((c) => [c.command, c]));
`;
writeFileSync(join(here, "..", "src", "generated", "commands.ts"), out);
console.log(`generated ${defs.length} commands`);
