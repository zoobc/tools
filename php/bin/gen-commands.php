// Writes src/commands_gen.php from ../spec/transactions/*.json so the package carries its own
// command table. Run from php/: php bin/gen-commands.php   (CI checks the result is current).
declare(strict_types=1);

$dir = __DIR__ . '/../../spec/transactions';
$files = array_filter(scandir($dir), fn($f) => str_ends_with($f, '.json') && $f !== 'index.json');
sort($files);
$defs = [];
foreach ($files as $f) {
    $d = json_decode(file_get_contents("$dir/$f"), true, 512, JSON_THROW_ON_ERROR);
    unset($d['license']);
    $defs[] = $d;
}
$out = "<?php\n// SPDX-License-Identifier: MIT\n// Copyright (c) 2024-2026 ZooBC Foundation and Roberto Capodieci\n"
    . "// GENERATED by bin/gen-commands.php from spec/transactions/*.json. Do not edit.\n\nreturn "
    . var_export($defs, true) . ";\n";
file_put_contents(__DIR__ . '/../src/commands_gen.php', $out);
echo 'generated src/commands_gen.php (' . count($defs) . " commands)\n";
