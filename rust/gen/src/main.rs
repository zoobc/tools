//! Writes zbc/src/commands_gen.rs from ../spec/transactions/*.json and one binary source per tool
//! under zbc-cli/src/bin/. Run from rust/: cargo run -p gen   (CI checks the result is current).

use std::fs;
use std::path::Path;

const HEADER: &str = "// SPDX-License-Identifier: MIT\n// Copyright (c) 2024-2026 ZooBC Foundation and Roberto Capodieci\n";

fn main() {
    let spec = Path::new("../spec/transactions");
    let mut names: Vec<String> = fs::read_dir(spec).expect("spec/transactions")
        .filter_map(|e| e.ok().map(|e| e.file_name().to_string_lossy().to_string()))
        .filter(|n| n.ends_with(".json") && n != "index.json")
        .collect();
    names.sort();
    let mut defs = Vec::new();
    for n in &names {
        let mut v: serde_json::Value = serde_json::from_str(&fs::read_to_string(spec.join(n)).unwrap()).unwrap();
        if let Some(o) = v.as_object_mut() {
            o.remove("license");
        }
        defs.push(v);
    }
    let json = serde_json::to_string_pretty(&serde_json::Value::Array(defs.clone())).unwrap();
    let mut src = String::from(HEADER);
    src.push_str("\n// GENERATED by gen from spec/transactions/*.json. Do not edit.\n\n");
    src.push_str("pub const COMMANDS_JSON: &str = r####\"");
    src.push_str(&json);
    src.push_str("\"####;\n");
    fs::write("zbc/src/commands_gen.rs", src).unwrap();

    let bin_dir = Path::new("zbc-cli/src/bin");
    fs::create_dir_all(bin_dir).unwrap();
    let mut count = 0;
    for d in &defs {
        let Some(bin) = d["binary"].as_str() else { continue };
        let cmd = d["command"].as_str().unwrap();
        let body = format!("{HEADER}\n// GENERATED by gen: the {cmd} command as its own program.\n\nfn main() {{\n    std::process::exit(zbc::cli::run_tool({cmd:?}, &std::env::args().skip(1).collect::<Vec<_>>()));\n}}\n");
        fs::write(bin_dir.join(format!("{bin}.rs")), body).unwrap();
        count += 1;
    }
    println!("generated zbc/src/commands_gen.rs ({} commands) and {count} zbc-cli/src/bin programs", defs.len());
}
